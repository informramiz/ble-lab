#!/usr/bin/env python3
"""Signs BLE Lab firmware images for over-the-air update.

  sign_firmware.py keygen            make a development ECDSA P-256 key pair, write the public key header
  sign_firmware.py sign IMAGE.bin    write IMAGE.signed.bin: the image plus version and signature

The private key lives in firmware/tools/keys/ (git-ignored). Only the public key header
(firmware/ble_lab/ota_public_key.h) is committed. Needs: pip install cryptography

Signed content: SHA-256 over  "BLFW1" | u32 size LE | u32 version code LE | SHA-256(image)
Signature: ECDSA P-256 over that digest, raw r||s (64 bytes).
Package layout: "BLFW" | u32 version code LE | 64-byte signature | image bytes.
Version code: major*10000 + minor*100 + patch, read from the "ble-lab X.Y.Z" string inside the image.
"""
import argparse
import hashlib
import re
import struct
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

ROOT = Path(__file__).resolve().parent
KEY_DIR = ROOT / "keys"
PRIVATE_KEY = KEY_DIR / "ota-dev-private.pem"
HEADER = ROOT.parent / "ble_lab" / "ota_public_key.h"
MAGIC = b"BLFW"
CONTEXT = b"BLFW1"


def manifest_message(size: int, version_code: int, image_sha256: bytes) -> bytes:
    return CONTEXT + struct.pack("<II", size, version_code) + image_sha256


def version_code_of(image: bytes) -> int:
    match = re.search(rb"ble-lab (\d+)\.(\d+)\.(\d+)", image)
    if not match:
        sys.exit("no 'ble-lab X.Y.Z' revision string in the image; is this the right .bin?")
    major, minor, patch = (int(g) for g in match.groups())
    return major * 10000 + minor * 100 + patch


def keygen(force: bool) -> None:
    if PRIVATE_KEY.exists() and not force:
        sys.exit(f"{PRIVATE_KEY} exists; pass --force to replace it (boards built with the old public key will reject new images)")
    KEY_DIR.mkdir(exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    PRIVATE_KEY.write_bytes(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    PRIVATE_KEY.chmod(0o600)
    point = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    body = ", ".join(f"0x{b:02x}" for b in point)
    HEADER.write_text(
        "// Trusted OTA signing key (ECDSA P-256, uncompressed point). Generated by tools/sign_firmware.py.\n"
        "// Public key only; the private key is git-ignored. Do not edit.\n"
        "#pragma once\n#include <stdint.h>\n"
        f"static const uint8_t OTA_PUBLIC_KEY[65] = {{{body}}};\n"
    )
    print(f"private key: {PRIVATE_KEY}\npublic key header: {HEADER}")


def sign(image_path: Path, output: Path | None, key_path: Path) -> None:
    image = image_path.read_bytes()
    if not image or image[0] != 0xE9:
        sys.exit("not an ESP32 app image (first byte must be 0xE9); use ble_lab.ino.bin, not the merged bin")
    key = serialization.load_pem_private_key(key_path.read_bytes(), password=None)
    version = version_code_of(image)
    message = manifest_message(len(image), version, hashlib.sha256(image).digest())
    der = key.sign(message, ec.ECDSA(hashes.SHA256()))
    r, s = decode_dss_signature(der)
    signature = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    out = output or image_path.with_suffix(".signed.bin")
    out.write_bytes(MAGIC + struct.pack("<I", version) + signature + image)
    print(f"{out}: version code {version}, {len(image)} B image, signed")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    gen = sub.add_parser("keygen")
    gen.add_argument("--force", action="store_true")
    sg = sub.add_parser("sign")
    sg.add_argument("image", type=Path)
    sg.add_argument("-o", "--output", type=Path)
    sg.add_argument("--key", type=Path, default=PRIVATE_KEY)
    args = parser.parse_args()
    keygen(args.force) if args.cmd == "keygen" else sign(args.image, args.output, args.key)


if __name__ == "__main__":
    main()
